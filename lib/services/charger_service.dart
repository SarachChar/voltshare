import 'package:supabase_flutter/supabase_flutter.dart';

import 'package:voltshare_app/models/charger_model.dart';

/// Charger-level reads and writes. Everything about the location (stations,
/// photos, businesses, promotions) is in StationService.
abstract class ChargerService {
  /// The host's chargers still in the approval flow (status 'review', 'setup'
  /// or 'rejected'), most recent first, with their station's name.
  Future<List<Charger>> getPendingChargersByHost(String hostId);

  /// The weekly availability rows for [chargerId], ordered by `day_of_week`
  /// (0 = Sunday .. 6 = Saturday).
  Future<List<ChargerAvailability>> getChargerAvailability(String chargerId);

  /// Inserts a new charger into [stationId] and returns the saved [Charger].
  /// Only charger fields are written: location, owner, photos and businesses
  /// belong to the station. New chargers start in 'review'.
  Future<Charger> createCharger({
    required String stationId,
    required String name,
    String chargerType,
    String connectorType,
    double powerKw,
    double pricePerKwh,
    String status,
  });

  /// Updates a charger's name and price, and its hardware specs when given.
  /// Pass null for [chargerType] / [connectorType] / [powerKw] to leave them
  /// unchanged (live chargers have locked specs). `status` and `station_id`
  /// are never changed here.
  Future<Charger> updateCharger({
    required String chargerId,
    required String name,
    required double pricePerKwh,
    String? chargerType,
    String? connectorType,
    double? powerKw,
  });

  /// Updates only the `status` of a charger ('available' / 'unavailable')
  /// and returns the saved [Charger]. Used by the host's on/off switch.
  Future<Charger> updateChargerStatus({
    required String chargerId,
    required String status,
  });

  /// Replaces all of a charger's weekly availability rows with [days].
  Future<void> replaceChargerAvailability({
    required String chargerId,
    required List<ChargerAvailability> days,
  });

  /// Inserts the weekly opening-hours rows for [chargerId] (one per day).
  Future<void> insertChargerAvailability({
    required String chargerId,
    required List<ChargerAvailability> days,
  });
}

/// Supabase-backed implementation that reads from the `chargers` table.
class ChargerSupabaseService implements ChargerService {
  final SupabaseClient _client = Supabase.instance.client;

  @override
  Future<List<Charger>> getPendingChargersByHost(String hostId) async {
    // Ownership is the station's host, so filter through an inner-joined
    // station and bring its name along.
    final List<dynamic> data = await _client
        .from('chargers')
        .select('*, stations!inner(name, host_id)')
        .eq('stations.host_id', hostId)
        .inFilter('status', Charger.pendingStatuses.toList())
        .order('created_at', ascending: false);

    return AllChargers.fromJson(data).chargers;
  }

  @override
  Future<List<ChargerAvailability>> getChargerAvailability(
    String chargerId,
  ) async {
    final List<dynamic> data = await _client
        .from('charger_availability')
        .select()
        .eq('charger_id', chargerId)
        .order('day_of_week', ascending: true);

    return data
        .map((row) => ChargerAvailability.fromJson(row as Map<String, dynamic>))
        .toList();
  }

  @override
  Future<Charger> createCharger({
    required String stationId,
    required String name,
    String chargerType = '',
    String connectorType = '',
    double powerKw = 0.0,
    double pricePerKwh = 0.0,
    String status = 'review',
  }) async {
    // `id` and `created_at` are generated by the DB. Ownership comes from the
    // station (RLS checks stations.host_id).
    final data = await _client
        .from('chargers')
        .insert({
          'station_id': stationId,
          'name': name,
          'charger_type': chargerType,
          'connector_type': connectorType,
          'power_kw': powerKw,
          'price_per_kwh': pricePerKwh,
          'status': status,
        })
        .select()
        .single();

    return Charger.fromJson(data);
  }

  @override
  Future<Charger> updateCharger({
    required String chargerId,
    required String name,
    required double pricePerKwh,
    String? chargerType,
    String? connectorType,
    double? powerKw,
  }) async {
    final data = await _client
        .from('chargers')
        .update({
          'name': name,
          'price_per_kwh': pricePerKwh,
          // Hardware specs only when the caller unlocked them.
          'charger_type': ?chargerType,
          'connector_type': ?connectorType,
          'power_kw': ?powerKw,
        })
        .eq('id', chargerId)
        .select()
        .single();

    return Charger.fromJson(data);
  }

  @override
  Future<Charger> updateChargerStatus({
    required String chargerId,
    required String status,
  }) async {
    final data = await _client
        .from('chargers')
        .update({'status': status})
        .eq('id', chargerId)
        .select()
        .single();

    return Charger.fromJson(data);
  }

  @override
  Future<void> replaceChargerAvailability({
    required String chargerId,
    required List<ChargerAvailability> days,
  }) async {
    // Clear the old week first so editing can't leave stale rows behind.
    await _client
        .from('charger_availability')
        .delete()
        .eq('charger_id', chargerId);
    await insertChargerAvailability(chargerId: chargerId, days: days);
  }

  @override
  Future<void> insertChargerAvailability({
    required String chargerId,
    required List<ChargerAvailability> days,
  }) async {
    if (days.isEmpty) return;
    final rows = days
        .map((day) => {
              'charger_id': chargerId,
              'day_of_week': day.dayOfWeek,
              'start_time': day.startTime,
              'end_time': day.endTime,
              'is_available': day.isAvailable,
            })
        .toList();

    await _client.from('charger_availability').insert(rows);
  }
}
